"""Write the checked-in runtime asset provenance report."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
manifest = json.loads((ROOT / "services/reconstruction/assets_manifest.json").read_text(encoding="utf-8"))
source_script = ROOT / "services/reconstruction/tools/build_interior_assets.py"
source_hash = hashlib.sha256(source_script.read_bytes()).hexdigest()
lines = ["# Interior asset provenance", "",
         "Production contains 11 project-generated originals and 12 models converted from the Sweet Home 3D BlendSwap CC0 pack. The project-generated geometry and textures are released as CC0-1.0 for this asset library. The source archive is retained locally and is not served by the site.", "",
         f"Imported pack SHA-256: `{manifest['source_sha256']}`. Its official upstream listing identifies this library as public domain; the downloaded copy came from the named GitHub mirror. Each imported item also passed its individual license-evidence check.", "",
         "| Runtime asset | Source / creator | License | Source SHA-256 | Runtime SHA-256 | Status |",
         "| --- | --- | --- | --- | --- | --- |"]
for path in sorted((ROOT / "public/interiors/models").glob("*.glb")):
    item = next((a for a in manifest["assets"] if a["id"] == path.stem), None)
    if item:
        lines.append(f"| `{path.stem}` | Sweet Home 3D BlendSwap CC0 / {item['original_creator']} | {item['license']} | `{item['source_model_sha256']}` | `{item['runtime_sha256']}` | {item['status']} |")
    else:
        runtime_hash = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"| `{path.stem}` | Project original / generated by `build_interior_assets.py` | CC0-1.0 | `{source_hash}` | `{runtime_hash}` | APPROVED |")
lines += ["", "The importer records source pack, model, creator, individual license evidence, dimensions, triangle count, runtime bytes and conversion diagnostics in [assets_manifest.json](services/reconstruction/assets_manifest.json). Unknown, mismatched or unlicensed models cannot enter the runtime catalog. Model 152 (desk) was rejected because its folder lacks individual CC0 evidence. Model 68 (wardrobe) needs review because its width differs materially from the catalog.", ""]
(ROOT / "INTERIOR_ASSET_PROVENANCE.md").write_text("\n".join(lines), encoding="utf-8")
